import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const require=createRequire(new URL('../../../../deepseek-harness-cnc/package.json',import.meta.url));
const {chromium}=require('playwright');
const artifacts=fileURLToPath(new URL('../../../.tmp-drawing-validation/',import.meta.url));
await mkdir(artifacts,{recursive:true});
const jobId='9d7023666ddd42d186fb7eb579e38b97';
const before=await (await fetch(`http://localhost:8090/api/v1/jobs/${jobId}`)).json();
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(jobId=>{
  sessionStorage.setItem('nexus.process-studio.login.v1','admin');
  localStorage.setItem('nexus.process-studio.task.v1',JSON.stringify({jobId,filename:'典型零件侧孔实体检查',view:{stage:'process',following:false}}));
},jobId);
try {
  await page.goto('http://localhost:3082/');
  const panel=page.getByRole('region',{name:'二维图纸依据'});
  await panel.waitFor();await panel.locator('summary').first().click();
  await panel.locator('.drawing-dimension-reviews > summary').click();
  await panel.getByRole('button',{name:/^PDF-DIM-6 ·/}).click();
  const form=panel.locator('.drawing-dimension-form');
  for(const feature of ['HF-14','HF-15','HF-16','HF-17']) await form.getByLabel(new RegExp(`^${feature} ·`)).check();
  const response=page.waitForResponse(r=>r.url().includes('/side-hole-check?') && r.request().method()==='POST');
  await form.getByRole('button',{name:'检查侧孔实体材料去除',exact:true}).click();
  const result=await response;assert.equal(result.status(),200,await result.text());
  const data=await result.json();assert.equal(data.can_accept,false);assert.equal(data.production_ready,false);
  assert.equal(data.target_contact_mm3,0);assert.ok(data.removed_volume_mm3>24);
  await form.getByText('圆柱刀具体积未侵入成品',{exact:true}).waitFor();
  const link=form.getByRole('link',{name:'下载本次剩余材料 STL',exact:true});
  const mesh=await fetch('http://localhost:3082'+await link.getAttribute('href'));
  assert.equal(mesh.status,200);assert.ok((await mesh.arrayBuffer()).byteLength>1000);
  await link.scrollIntoViewIfNeeded();await page.screenshot({path:artifacts+'side-hole-solid-check.png'});
  await form.getByLabel('加入钻尖与钻深检查',{exact:true}).check();
  await form.getByRole('button',{name:'检查侧孔实体材料去除',exact:true}).click();
  await form.getByRole('alert').filter({hasText:'请填写实际钻尖角'}).waitFor();
  await form.getByLabel('钻尖角（°）',{exact:true}).fill('118');
  await form.getByLabel('同时检查刀杆与刀柄',{exact:true}).check();
  for(const [label,value] of [['刃长（mm）','10'],['从钻尖到刀柄的伸出长度（mm）','20'],['刀杆直径（mm）','1.5'],['刀柄直径（mm）','8'],['刀柄长度（mm）','15']])await form.getByLabel(label,{exact:true}).fill(value);
  await form.getByLabel('刀具几何及钻深依据',{exact:true}).fill('隔离任务参考测试几何：118°，10/20 mm，杆径1.5、柄径8、柄长15；不代表客户实际刀具。');
  const drillResponse=page.waitForResponse(r=>r.url().includes('/side-hole-check?') && r.request().method()==='POST');
  await form.getByRole('button',{name:'检查侧孔实体材料去除',exact:true}).click();
  const drillResult=await drillResponse;assert.equal(drillResult.status(),200,await drillResult.text());
  const drill=await drillResult.json();assert.equal(drill.geometry_scope,'conical_tip_and_cylindrical_body');
  assert.equal(drill.can_accept,false);assert.equal(drill.non_cutting_clearance_status,'passed');
  assert.ok(drill.removed_volume_mm3>data.removed_volume_mm3);
  assert.ok(drill.hole_depths[0].tip_length_mm>.4 && drill.hole_depths[0].tip_length_mm<.5);
  assert.ok(drill.machine_assessment.checks.some(c=>c.code==='station_and_travel' && c.status==='review'));
  await form.locator('.drawing-hole-check').waitFor();
  await form.locator('.drawing-hole-check').scrollIntoViewIfNeeded();
  await page.screenshot({path:artifacts+'side-hole-drill-tip-check.png'});
  await form.getByLabel('完整直径终点偏移（mm，正值更深）',{exact:true}).fill('-0.46');
  const shorterResponse=page.waitForResponse(r=>r.url().includes('/side-hole-check?') && r.request().method()==='POST');
  await form.getByRole('button',{name:'检查侧孔实体材料去除',exact:true}).click();
  const shorterResult=await shorterResponse;assert.equal(shorterResult.status(),200,await shorterResult.text());
  const shorter=await shorterResult.json();assert.equal(shorter.can_accept,false);
  assert.equal(shorter.target_contact_mm3,0);assert.ok(shorter.remaining_cylindrical_segments_mm3>2);
  assert.equal(shorter.readiness.status,'blocked');
  assert.ok(shorter.readiness.checks.some(c=>c.code==='selected_hole_residual' && c.status==='blocked'));
  assert.ok(shorter.readiness.checks.some(c=>c.code==='hole_residual' && c.feature_id==='HF-14'));
  await form.getByText('工序接受前需处理 · 存在阻碍',{exact:true}).waitFor();
  await form.locator('.drawing-hole-check').scrollIntoViewIfNeeded();await page.screenshot({path:artifacts+'side-hole-drill-retracted-check.png'});
  const materialResponse=page.waitForResponse(r=>r.url().endsWith('/remaining-stock.stl') && r.request().method()==='GET');
  await form.getByRole('button',{name:'查看本次剩余材料',exact:true}).click();
  const material=page.getByRole('dialog',{name:'本次侧孔检查剩余材料',exact:true});
  await material.waitFor();assert.equal((await materialResponse).status(),200);
  await material.locator('.model-viewer > canvas').waitFor();
  await page.waitForTimeout(1500);
  const canvas=material.locator('.model-viewer > canvas');const box=await canvas.boundingBox();assert.ok(box.width>500 && box.height>300);
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  await page.mouse.move(box.x+box.width/2+100,box.y+box.height/2+50,{steps:10});await page.mouse.up();
  await page.mouse.wheel(0,-100);await page.waitForTimeout(300);
  await page.screenshot({path:artifacts+'side-hole-remaining-material-preview.png'});
  await page.keyboard.press('Escape');await material.waitFor({state:'detached'});
  await form.getByRole('button',{name:'查看本次剩余材料',exact:true}).click();await material.waitFor();
  await material.getByRole('button',{name:'关闭材料预览',exact:true}).click();await material.waitFor({state:'detached'});
  const after=await (await fetch(`http://localhost:8090/api/v1/jobs/${jobId}`)).json();
  assert.deepEqual(after.plan.setups,before.plan.setups,'sandbox check must not accept, add or edit operations');
  assert.deepEqual(errors,[]);
  console.log(`PASS: cylinder ${data.removed_volume_mm3} mm³; reference drill target intrusion ${drill.target_contact_mm3} mm³; retracted drill intrusion ${shorter.target_contact_mm3} and cylindrical residual ${shorter.remaining_cylindrical_segments_mm3} mm³; machine ${drill.machine_assessment.status}; no plan changes.`);
}catch(error){await page.screenshot({path:artifacts+'side-hole-solid-failure.png'});throw error;}finally{await browser.close();}
