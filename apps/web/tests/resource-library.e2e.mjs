import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const require = createRequire(new URL('../../../../deepseek-harness-cnc/package.json', import.meta.url));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1360, height: 850 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => {
  sessionStorage.setItem('nexus.process-studio.login.v1', 'admin');
  localStorage.removeItem('nexus.process-studio.task.v1');
});
const dialog = page.getByRole('dialog', { name: '资源库', exact: true });
try {
  await page.goto('http://127.0.0.1:3082');
  await page.getByRole('button', { name: '关闭上传', exact: true }).click();
  await page.getByRole('button', { name: '资源库', exact: true }).click();
  await dialog.locator('.studio-resource-grid article').first().waitFor();
  const total = await dialog.locator('.studio-resource-grid article').count();
  assert.ok(total > 0);
  const headingTop = (await dialog.locator('.studio-resource-heading').boundingBox()).y;
  const grid = dialog.locator('.studio-resource-grid');
  await grid.evaluate(element => { element.scrollTop = 300; });
  assert.equal((await dialog.locator('.studio-resource-heading').boundingBox()).y, headingTop);
  assert.equal(await dialog.evaluate(element => element.scrollHeight > element.clientHeight), false);
  await grid.evaluate(element => { element.scrollTop = 0; });
  await mkdir('../../.tmp-progress-validation', { recursive: true });
  await page.screenshot({ path: '../../.tmp-progress-validation/resource-operations.png' });
  await dialog.getByLabel('搜索资源').fill('不存在的资源12345');
  await dialog.getByText('没有符合条件的资源，请调整搜索或筛选条件。').waitFor();
  await dialog.getByLabel('搜索资源').fill('');
  await dialog.getByLabel('筛选设备').selectOption('citizen-cincom-l32');
  const filtered = await dialog.locator('.studio-resource-grid article').count();
  assert.ok(filtered > 0 && filtered <= total);
  await dialog.locator('summary').first().click();
  assert.ok(await dialog.locator('details[open]').count());
  console.log(`PASS 工序库：真实数据 ${total} 项，设备筛选 ${filtered} 项，搜索与详情正常`);
  await dialog.getByRole('button', { name: /刀具库/ }).click();
  await dialog.locator('.tool-library-list article').first().waitFor();
  assert.equal(await dialog.locator('.tool-library-popover>header').isVisible(), false);
  await page.screenshot({ path: '../../.tmp-progress-validation/resource-tools.png' });
  assert.ok(await dialog.locator('.tool-library-list article').count() > 0);
  await dialog.getByLabel('搜索刀具').fill('不存在的刀具12345');
  assert.equal(await dialog.locator('.tool-library-list article').count(), 0);
  await dialog.getByLabel('搜索刀具').fill('');
  assert.equal(await dialog.getByText('登记现场刀具', { exact: true }).count(), 0);
  console.log('PASS 无任务时刀具目录可浏览和搜索');
  await dialog.getByRole('button', { name: /设备库/ }).click();
  assert.ok(await dialog.locator('.studio-resource-grid article').count() > 0);
  await dialog.getByLabel('搜索资源').fill('L32');
  assert.equal(await dialog.locator('.studio-resource-grid article').count(), 1);
  await dialog.locator('summary').click();
  await mkdir('../../.tmp-progress-validation', { recursive: true });
  await page.screenshot({ path: '../../.tmp-progress-validation/resource-library.png' });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'detached' });
  assert.equal(await page.getByRole('button', { name: '资源库', exact: true }).evaluate(element => element === document.activeElement), true);
  console.log('PASS 设备搜索、详情、Escape关闭及焦点返回');
  await page.route('**/api/v1/operation-library', route => route.fulfill({ status: 503 }));
  await page.getByRole('button', { name: '资源库', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  await page.unroute('**/api/v1/operation-library');
  await dialog.getByRole('button', { name: '重新加载' }).click();
  await dialog.locator('.studio-resource-grid article').first().waitFor();
  console.log('PASS 加载失败后重试恢复');
  await page.setViewportSize({ width: 390, height: 844 });
  const bounds = await dialog.boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
  assert.equal(await dialog.evaluate(element => element.scrollWidth > element.clientWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS 小屏布局及无前端异常');
} finally { await browser.close(); }
