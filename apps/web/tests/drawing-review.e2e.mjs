import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir,readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const require=createRequire(new URL('../../../../deepseek-harness-cnc/package.json',import.meta.url));
const {chromium}=require('playwright');
const artifacts=fileURLToPath(new URL('../../../.tmp-drawing-validation/',import.meta.url));
await mkdir(artifacts,{recursive:true});
const jobId=(await readFile(artifacts+'job-id.txt','utf8')).trim();
assert.equal(jobId,'9d7023666ddd42d186fb7eb579e38b97','Only the isolated drawing validation task may be edited');
const job=await (await fetch(`http://localhost:8090/api/v1/jobs/${jobId}`)).json();
const index=job.drawing_analysis.dimensions.findIndex(d=>d.role==='radial_hole' && d.nominal===1.5);
assert.ok(index>=0);
const id=`PDF-DIM-${index+1}`;
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(jobId=>{
  sessionStorage.setItem('nexus.process-studio.login.v1','admin');
  localStorage.setItem('nexus.process-studio.task.v1',JSON.stringify({jobId,filename:'典型零件图纸审核验证',view:{stage:'process',following:false}}));
},jobId);
try {
  await page.goto('http://localhost:3082/');
  const panel=page.getByRole('region',{name:'二维图纸依据'});
  await panel.waitFor();
  await panel.locator('summary').first().click();
  await panel.locator('.drawing-dimension-reviews > summary').click();
  const row=panel.getByRole('button',{name:new RegExp(`^${id} ·`)});
  await row.click();
  const form=panel.locator('.drawing-dimension-form');
  for(const feature of ['HF-14','HF-15','HF-16','HF-17']) await form.getByLabel(new RegExp(`^${feature} ·`)).check();
  await form.getByRole('button',{name:'查看侧向孔刀路草案',exact:true}).click();
  await form.getByText('孔位中心线 · 尚未验证',{exact:true}).waitFor();
  assert.equal(await form.locator('.drawing-hole-draft .stock-note').count(),4);
  assert.match(await form.locator('.drawing-hole-draft').innerText(),/偏置 8\.100 mm/);
  assert.equal(await form.getByLabel('上偏差',{exact:true}).inputValue(),'0.08');
  assert.equal(await form.getByLabel('下偏差',{exact:true}).inputValue(),'0.03');
  await form.getByLabel('审核人',{exact:true}).fill('隔离验证任务');
  await form.getByLabel('图纸页码、引线与核对依据',{exact:true}).fill('独立验证任务：第1页 B-B Ø1.50 +0.08/+0.03 (4)，核对四个侧孔与 HF-14～HF-17；仅确认图纸关联，不确认加工质量。');
  await page.screenshot({path:artifacts+'side-hole-draft.png'});
  const saved=page.waitForResponse(response=>response.url().includes(`/drawing-dimensions/${id}/review`) && response.request().method()==='PUT');
  await form.getByRole('button',{name:'保存读数与关联',exact:true}).click();
  const response=await saved;assert.equal(response.status(),200,await response.text());
  const data=await response.json();
  const requirement=data.plan.manufacturing_requirements.requirements.find(r=>r.id===id);
  assert.equal(requirement.verification_status,'pending_measurement');
  assert.equal(requirement.mapping_status,'matched');
  assert.equal(requirement.minimum,1.53);assert.equal(requirement.maximum,1.58);
  assert.equal(data.plan.coverage.production_ready,false);
  await panel.getByRole('button',{name:new RegExp(`^${id} .*读数已核对 · 待检测`)}).waitFor();
  await page.screenshot({path:artifacts+'drawing-review-saved.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: 真实四个偏置孔草案、PDF公差审核、关联保存、仍待检测且不可生产；只编辑隔离验证任务。');
} catch(error) {await page.screenshot({path:artifacts+'drawing-review-failure.png'});throw error;} finally {await browser.close();}
