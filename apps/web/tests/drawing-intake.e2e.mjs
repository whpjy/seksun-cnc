import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir,readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const require=createRequire(new URL('../../../../deepseek-harness-cnc/package.json',import.meta.url));
const {chromium}=require('playwright');
const artifacts=fileURLToPath(new URL('../../../.tmp-drawing-validation/',import.meta.url));
await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:950}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>sessionStorage.setItem('nexus.process-studio.login.v1','admin'));
const uploads=[];let prompt;
await page.route('**/harness/api/session/create',route=>route.fulfill({json:{result:{ok:true,value:{sessionId:'paired-upload-test'}}}}));
await page.route('**/harness/api/session/uploadFileBinary?*',async route=>{uploads.push(new URL(route.request().url()).searchParams.get('name'));await route.fulfill({json:{ok:true,value:{receiptId:'receipt-'+uploads.length}}});});
await page.route('**/harness/api/session/rename',route=>route.fulfill({json:{result:{ok:true,value:{}}}}));
await page.route('**/harness/api/session/prompt',route=>{prompt=route.request().postDataJSON().payload.args.request;return route.fulfill({json:{result:{ok:true,value:{}}}});});
try{
  await page.goto('http://localhost:3082/');
  await page.getByRole('button',{name:'新建任务',exact:true}).click();
  const start=page.getByRole('button',{name:'开始工艺设计',exact:true});
  assert.equal(await start.isEnabled(),false);
  await page.locator('input[type=file][accept=".stp,.step"]').setInputFiles({name:'test-part.stp',mimeType:'application/step',buffer:Buffer.from('STEP')});
  assert.equal(await start.isEnabled(),false,'STEP alone must not start paired planning');
  await page.locator('input[type=file][accept=".pdf,application/pdf"]').setInputFiles({name:'test-part.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4')});
  await page.screenshot({path:artifacts+'paired-upload.png'});
  await start.click();
  await page.locator('.studio-upload').waitFor({state:'hidden'});
  assert.deepEqual(uploads,['test-part.stp','test-part.pdf']);
  assert.equal(prompt.content.filter(x=>x.type==='file').length,2);
  assert.match(prompt.content.find(x=>x.type==='text').text,/drawing_path/);
  const jobId=(await readFile(artifacts+'job-id.txt','utf8')).trim();
  await page.addInitScript(jobId=>localStorage.setItem('nexus.process-studio.task.v1',JSON.stringify({jobId,filename:'典型零件配对图纸验证',view:{stage:'process',following:false}})),jobId);
  await page.reload();
  await page.getByRole('region',{name:'二维图纸依据'}).waitFor();
  await page.getByRole('region',{name:'二维图纸依据'}).locator('summary').first().click();
  await page.getByText('SUS316L',{exact:true}).first().waitFor();
  await page.getByRole('button',{name:'第一步：毛坯选择',exact:true}).click();
  await page.getByText('实心圆棒 · 初始内径 0 mm',{exact:true}).waitFor();
  await page.screenshot({path:artifacts+'drawing-stock.png'});
  await page.getByRole('button',{name:'工艺规则',exact:true}).click();
  await page.getByText('粗加工后保留的精加工余量',{exact:true}).waitFor();
  await page.screenshot({path:artifacts+'machining-rules.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: 配对上传、两个附件进入规划、PDF依据与实心毛坯、企业余量规则页面；未修改历史任务。');
}catch(error){await page.screenshot({path:artifacts+'drawing-e2e-failure.png'});console.log((await page.locator('body').innerText()).slice(0,2500));throw error;}finally{await browser.close();}
